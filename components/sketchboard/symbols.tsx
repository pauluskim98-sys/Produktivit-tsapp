const legacy: Record<string, keyof typeof symbols> = {
  "☀️": "Sonne",
  "⛰️": "Berge",
  "🏔️": "Berge",
  "🌴": "Palme",
  "✈️": "Flugzeug",
  "❤️": "Herz",
  "⭐": "Stern",
  "🌙": "Mond",
  "🌊": "Wellen",
  "🌴️": "Palme",
};
export function SymbolArt({
  name,
  stroke,
  fill,
  width = 1.5,
}: {
  name: string;
  stroke: string;
  fill: string;
  width?: number;
}) {
  const key = legacy[name] ?? name;
  const Icon = Object.hasOwn(symbols, key)
    ? symbols[key as keyof typeof symbols]
    : null;
  return Icon ? (
    <Icon
      className="lm-symbol-art"
      stroke={stroke}
      fill={fill}
      strokeWidth={width}
      aria-hidden
    />
  ) : (
    <svg className="lm-symbol-art" viewBox="0 0 100 100" aria-hidden>
      <text
        x="50"
        y="53"
        textAnchor="middle"
        dominantBaseline="central"
        fontSize="70"
      >
        {name}
      </text>
    </svg>
  );
}
